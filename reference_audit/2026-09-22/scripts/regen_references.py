def narratives(args) -> None:
    import litellm

    from policybench.case_reference_explanations import (
        MAX_TOKENS,
        REFERENCE_MODEL,
        TEMPERATURE,
        _prompt,
        _scenario_summary,
    )

    out = Path(args.out_dir)
    meta = json.loads((out / "reference_outputs.csv.meta.json").read_text())
    traces = json.loads((out / "reference_traces.json").read_text())
    scenarios = pd.read_csv(BUNDLE / "scenarios.csv").set_index("scenario_id", drop=False)
    explanations = pd.read_csv(args.explanations)
    todo = []
    for revision in meta["revisions"]:
        for item in revision["changed"]:
            mask = (explanations["scenario_id"] == item["scenario_id"]) & (
                explanations["variable"] == item["variable"]
            )
            current = explanations.loc[mask, "reference_value"]
            if len(current) and abs(float(current.iloc[0]) - item["regenerated"]) <= 1e-6:
                continue
            todo.append((revision, item))
    frozen = pd.read_csv(BUNDLE / "reference_outputs.csv").set_index(["scenario_id", "variable"])["value"]
    only = set(args.frozen) if args.frozen else set(FROZEN_NARRATIVES)
    for (scenario_id, variable), grounding in FROZEN_NARRATIVES.items():
        if f"{scenario_id}:{variable}" not in only and (scenario_id, variable) not in only:
            continue
        todo.append(
            (
                {"frozen_grounding": grounding},
                {
                    "scenario_id": scenario_id,
                    "variable": variable,
                    "regenerated": float(frozen[(scenario_id, variable)]),
                    "trace_key": f"frozen|{scenario_id}|{variable}",
                },
            )
        )

    def grounding_for(revision) -> str:
        if "frozen_grounding" in revision:
            return revision["frozen_grounding"]
        if revision["kind"] == "convention":
            return conventions()[revision["convention"]]["grounding"]
        cause = json.loads((HERE / "root_causes.json").read_text())[revision["root_cause"]]
        return (
            f"The reference applies the fix for an engine defect fixed upstream "
            f"({cause['upstream']}): {cause['alternative_reading']}"
        )

    async def one(revision, item, extra=""):
        row = scenarios.loc[item["scenario_id"]]
        traced = traces[item.get("trace_key", f"{item['scenario_id']}|{item['variable']}")]
        trace = traced["trace"]
        prompt = _prompt(
            "us",
            _scenario_summary(row),
            item["variable"],
            traced["pe_variable"],
            item["regenerated"],
            YEAR,
            trace,
            grounding=grounding_for(revision) + extra,
        )
        response = await litellm.acompletion(
            model=REFERENCE_MODEL,
            messages=[{"role": "user", "content": prompt}],
            temperature=TEMPERATURE,
            max_tokens=MAX_TOKENS,
        )
        text = response.choices[0].message.content.strip()
        lines = text.split("\n")
        if lines and lines[0].lstrip().startswith("#"):
            text = "\n".join(lines[1:]).strip()
        return item, text, len(trace.splitlines())

    async def run_all():
        return await asyncio.gather(*(one(c, item) for c, item in todo))

    results = asyncio.run(run_all())
    for index, (item, text, n_lines) in enumerate(results):
        key = (item["scenario_id"], item["variable"])
        required = FROZEN_REQUIRED.get(key, [])
        for attempt in range(3):
            missing = [figure for figure in required if figure not in text]
            if not missing:
                break
            extra = (
                " The narrative must state these figures and the fact behind each: "
                + ", ".join(missing)
                + "."
            )
            item, text, n_lines = asyncio.run(one(todo[index][0], item, extra))
        missing = [figure for figure in required if figure not in text]
        if missing:
            raise SystemExit(f"{key}: narrative still omits {missing}")
        if key in HAND_CORRECTED:
            print(f"--- draft replaced by HAND_CORRECTED: {key[0]} {key[1]}\n{text}\n")
            text = HAND_CORRECTED[key]
            assert not [figure for figure in required if figure not in text], key
        results[index] = (item, text, n_lines)
    for item, text, n_lines in results:
        mask = (explanations["scenario_id"] == item["scenario_id"]) & (
            explanations["variable"] == item["variable"]
        )
        explanations.loc[mask, "reference_value"] = item["regenerated"]
        explanations.loc[mask, "trace_lines"] = n_lines
        explanations.loc[mask, "explanation"] = text
        explanations.loc[mask, "error"] = pd.NA
        print(f"--- {item['scenario_id']} {item['variable']} ({item['regenerated']:.2f})\n{text}\n")
    # An excluded output keeps its frozen reference, so its narrative is the
    # frozen bundle's unless FROZEN_NARRATIVES rewrote it above.
    excluded = {
        (e["scenario_id"], e["variable"])
        for e in json.loads(Path(args.exclusions).read_text())["exclusions"]
    }
    pristine = pd.read_csv(PRISTINE_EXPLANATIONS).set_index(["scenario_id", "variable"])
    restored = []
    for idx, row in explanations.iterrows():
        key = (row["scenario_id"], row["variable"])
        if key not in excluded or key in FROZEN_NARRATIVES:
            continue
        if abs(float(row["reference_value"]) - float(frozen[key])) <= 1e-6:
            continue
        for column in explanations.columns:
            if column in pristine.columns:
                explanations.loc[idx, column] = pristine.loc[key, column]
        restored.append(f"{key[0]}:{key[1]}")
    explanations.to_csv(out / "us_case_reference_explanations.csv", index=False)
    print(f"rewrote {len(todo)} narratives; restored the frozen narrative of {restored}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("step", choices=["references", "frozen-traces", "narratives"])
    parser.add_argument("--exclusions")
    parser.add_argument("--explanations")
    # Rewrite only these FROZEN_NARRATIVES (scenario_id:variable); default all.
    parser.add_argument("--frozen", nargs="*")
    parser.add_argument("--out-dir", required=True)
    args = parser.parse_args()
    {"references": references, "frozen-traces": frozen_traces, "narratives": narratives}[args.step](args)


if __name__ == "__main__":
    main()
