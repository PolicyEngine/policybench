        sim = Simulation(situation=build_situation(scenario))
        sim.trace = True
        pe_variable = _pe_variable_for_output(variable, "us")
        sim.calculate(pe_variable, YEAR)
        tree = _find_target_tree(sim.tracer.trees, pe_variable)
